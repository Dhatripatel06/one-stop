/* =========================================================
   LEGACY PRODUCT IMAGES IN THE CODEBASE
   New product images are stored in Cloudinary (server/cloudinary.js).
   Products created before the Cloudinary migration point at photos in
   this repository (/OSS_001.jpg …). This module validates those paths,
   lists them (the migration source), and reports missing files so the
   website can show a placeholder.

   The deployed server cannot see the website's static files, so the build
   writes images/manifest.json and the API checks paths against it.
========================================================= */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { HttpError } from "./http.js";
import { parseCloudinaryUrl } from "./cloudinary.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PRODUCT_IMAGE_DIR = "images/products";
export const PLACEHOLDER_IMAGE = "/images/placeholder.svg";
const MANIFEST = path.join(ROOT, "images", "manifest.json");

const ROOT_FILE = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,120}\.(jpe?g|png|webp)$/i;
const LOCAL_PATH = /^\/(?:images\/products\/)?[A-Za-z0-9][A-Za-z0-9_.-]{0,120}\.(jpe?g|png|webp)$/i;
// Files at the root that must not be offered as product photos: the logo, and
// .webp copies whose names point at the wrong product (see docs/IMPORT_REPORT.md).
const NOT_PRODUCT_IMAGES = new Set([
  "538820.jpg", "538822.jpg",
  "OSS_008.webp", "OSS_011.webp", "OSS_013.webp", "OSS_016.webp", "OSS_020.webp", "OSS_022.webp", "OSS_024.webp"
]);

/* ---------------------------------------------------------
   PATHS
--------------------------------------------------------- */

// Returns { kind: "local" | "external", path } or null when not acceptable.
export function normalizeImagePath(value) {
  const text = String(value ?? "").trim();
  if (!text) return null;
  if (/[\\\u0000-\u001f]/.test(text) || text.includes("..") || /^[a-z]:/i.test(text) || text.startsWith("//")) return null;

  if (/^https?:\/\//i.test(text)) {
    let url;
    try { url = new URL(text); } catch { return null; }
    const local = url.hostname === "127.0.0.1" || url.hostname === "localhost";
    if (url.protocol !== "https:" && !(local && url.protocol === "http:")) return null;
    if (url.username || url.password) return null;
    return { kind: "external", path: url.toString() };
  }

  const candidate = text.startsWith("/") ? text : `/${text}`;
  if (!LOCAL_PATH.test(candidate)) return null;
  return { kind: "local", path: candidate };
}

// Legacy documents store "OSS_001.jpg"; the website uses "/OSS_001.jpg".
export function toPublicPath(value) {
  const normalized = normalizeImagePath(value);
  return normalized ? normalized.path : null;
}

/* ---------------------------------------------------------
   AVAILABLE IMAGES
--------------------------------------------------------- */

function scanFolder() {
  const list = [];
  for (const name of fs.readdirSync(ROOT)) {
    if (ROOT_FILE.test(name) && !NOT_PRODUCT_IMAGES.has(name)) list.push(`/${name}`);
  }
  const dir = path.join(ROOT, PRODUCT_IMAGE_DIR);
  if (fs.existsSync(dir)) {
    for (const name of fs.readdirSync(dir)) {
      if (ROOT_FILE.test(name)) list.push(`/${PRODUCT_IMAGE_DIR}/${name}`);
    }
  }
  return list.sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
}

function readManifest() {
  try {
    const data = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
    return Array.isArray(data.images) ? data.images : [];
  } catch {
    return null;
  }
}

let cache = null;

// On Vercel the static files are not inside the function, so use the manifest.
export function listLocalImages() {
  if (cache) return cache;
  const fromDisk = process.env.VERCEL ? null : scanFolder();
  const list = fromDisk ?? readManifest();
  if (!list) {
    throw new HttpError(503, "The product image list (images/manifest.json) is missing. Run npm run build and redeploy.");
  }
  cache = list;
  setTimeout(() => { cache = null; }, 5000).unref?.();
  return list;
}

export function localImageExists(publicPath) {
  try {
    return listLocalImages().includes(publicPath);
  } catch {
    return false;
  }
}

export function writeManifest() {
  const images = scanFolder();
  fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
  const body = JSON.stringify({ note: "Generated by npm run build. Lists product images served from this repository.", images }, null, 2) + "\n";
  const current = fs.existsSync(MANIFEST) ? fs.readFileSync(MANIFEST, "utf8") : "";
  if (current !== body) fs.writeFileSync(MANIFEST, body);
  cache = null;
  return images;
}

// "ok" (Cloudinary or existing project file) | "missing" (file not in project) | "external" | "none"
export function imageStatus(images) {
  const first = (images || [])[0];
  if (!first) return "none";
  const normalized = normalizeImagePath(first);
  if (!normalized) return "missing";
  if (normalized.kind === "external") return parseCloudinaryUrl(normalized.path) ? "ok" : "external";
  return localImageExists(normalized.path) ? "ok" : "missing";
}
